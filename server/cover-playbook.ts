/** 单张人物参考照在提示词里的呈现方式。 */
export type PlaybookPersonRef = {path: string; purpose: string}

/**
 * 第一步 + 第二步：把样本摘要交给 Agent，产出分三类的可执行设计规范。
 * sampleSummaries 是客观特征（8×8 缩略统计），personRefCount 只用于提示不要照搬人脸。
 */
export function coverAnalysisPrompt(sampleSummaries: string[], sampleFiles: string[], personRefCount: number) {
  return [
    `以下是一组封面样本的客观视觉特征（每张缩成 8×8 后统计），共 ${sampleSummaries.length} 张：`,
    ...sampleSummaries.map((line, i) => `${i + 1}. ${line}`),
    '',
    '样本原图（若你支持读取图片，可结合这些路径核对构图；不支持就只用上面的客观特征，不要臆造看不到的细节）：',
    ...sampleFiles.map((file, i) => `${i + 1}. ${file}`),
    '',
    `本次已提供 ${personRefCount} 张固定出镜人物的授权参考照。规范里只写「人物身份约束」，不要试图从样本里反推或指定某张具体人脸。`,
    '',
    '请逐张归纳画面的视觉规律（主体位置比例动作表情、标题留白区处理、配色材质光影背景、缩略图阅读顺序），再整理成一套可执行的《封面底图设计规范》，严格分三类输出：',
    'A. 必须遵守的稳定规则（通用、可复用）；',
    'B. 可按视频主题灵活调整的设计变量；',
    'C. 不能照搬的账号专属元素与版权元素。',
    '',
    '规范至少覆盖：主体策略、竖向三分法构图、上方标题留白区、人物规范、配色策略、主题概念设计、图标使用、手部约束、尺寸安全区、缩略图检查、生成失败后的修改流程；并加入「遮挡测试」与「缩略图测试」两项自检。',
    '注意：样本上的文字是后期排版的产物，不要把它当成画面规律提炼；标题字数、字号、层级由套版统一处理，不写进规范。',
    '只提炼抽象规律，禁止照搬样本中的文案、人物、Logo、角色形象、插画或高度相似的版式。',
    '用中文分条输出，每条不超过 45 字，不要 Markdown 代码块，不要复述样本的具体文字。',
  ].join('\n')
}

