/**
 * 第三步 + 第四步：把已确认的规范 + 真人参考照路径封装成一次任务的生图提示词。
 * 这是「按规范写提示词」按钮真正发给 Agent 的内容——规则全埋在这里，用户只改标题和重点词。
 * title 只作为画面情绪的参考信息写进去，明确禁止画到画面上。
 */
export function coverDirectorPrompt(input: {
  topic: string
  platform: string
  title: string
  keywords: string
  spec: string
  personRefs: PlaybookPersonRef[]
}) {
  const {topic, platform, title, keywords, spec, personRefs} = input
  const identity = personRefs.length
    ? [
        '本次为「固定真人出镜」封面底图。以下是用户已授权的人物参考照，生成时保持同一人物的真实身份：',
        ...personRefs.map((ref, i) => `${i + 1}. 路径：${ref.path}\n   用途：${ref.purpose}`),
        '身份约束：保持真实脸型、五官比例、发型、年龄感与自然肤色；每张底图只出现一个人物；根据视频主题设计合适的服装、动作和表情；不得生成模板化网红脸，不得出现巨大前景手、畸形手指或重复肢体。',
      ].join('\n')
    : '本次「不使用真人出镜」。人物区改为产品主体或抽象符号，并在提示词里说明选择理由；不得凭空指定某个具体人物或虚构身份。'

  return [
    `作品主题：${topic || '（未填写）'}`,
    `发布平台：${platform || '抖音'}`,
    `作品标题（仅供判断画面情绪，禁止画进画面；标题由套版用字体排上去）：${title || '（未填写）'}`,
    `重点词（仅供判断第一视觉，禁止画进画面）：${keywords || '（未指定，从主题提炼）'}`,
    '',
    '【已确认的底图设计规范】',
    spec || '尚未建立历史封面规范：按下面的通用稳定规则执行，不要臆造某位博主的风格。',
    '',
    '【真人身份参考】',
    identity,
    '',
    '【必须遵守的稳定规则】',
    COVER_STABLE_RULES,
    '',
    '【可按主题调整的设计变量】',
    COVER_VARIABLES,
    '',
    '【不能照搬的元素】',
    COVER_FORBIDDEN,
    '',
    '【执行步骤】',
    COVER_STEPS,
    '',
    '【生成后自检清单】',
    COVER_CHECKLIST,
    '',
    '现在输出一段完整、可直接交给图像生成模型的中文提示词。要求：只描述画面、构图、光影、配色与留白，按发布平台档案的比例出原生底图；严禁出现任何文字、字幕、水印或疑似文字的笔画；结构清晰、分节列出；不要输出 JSON，不要 Markdown 代码块，不要解释你的推理。',
  ].join('\n')
}

